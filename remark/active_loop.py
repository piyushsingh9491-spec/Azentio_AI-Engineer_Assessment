"""Simulated active learning with the TF-IDF baseline.

    python -m remark.active_loop --strategy uncertainty|random|both --seed-labels 60 \
        --batch 30 --rounds 10 [--seeds 0 1 2]

An oracle reveals hidden train.csv labels for the rows each strategy picks.
After every round the baseline is retrained on the labelled rows and scored
on test.csv (evaluation only). Both strategies share the same seed-label set
for a given random seed. `--strategy both` (default) also writes
reports/active_learning.md.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from remark.data import label_ids, load_split
from remark.metrics import macro_f1
from remark.train_baseline import fit_baseline

STRATEGIES = ("uncertainty", "random")
TARGET_FRACTION = 0.95


def entropy(probs: np.ndarray) -> np.ndarray:
    return -np.sum(probs * np.log(np.clip(probs, 1e-12, 1.0)), axis=1)


def fit_and_score(train_rows: pd.DataFrame, test: pd.DataFrame):
    predictor = fit_baseline(train_rows)
    pred = predictor.predict_proba(test["narration"].tolist()).argmax(axis=1)
    return predictor, macro_f1(label_ids(test), pred)


def run(strategy: str, train: pd.DataFrame, test: pd.DataFrame, seed: int,
        seed_labels: int, batch: int, rounds: int) -> list[tuple[int, float]]:
    """Returns [(n_labels, test macro-F1)] for round 0 (seed set) .. rounds."""
    seed_rng = np.random.default_rng(seed)
    labelled = list(seed_rng.choice(len(train), size=seed_labels, replace=False))
    pick_rng = np.random.default_rng(seed + 10_000)  # only used by the random strategy
    curve = []
    for round_no in range(rounds + 1):
        predictor, f1 = fit_and_score(train.iloc[labelled], test)
        curve.append((len(labelled), f1))
        if round_no == rounds:
            break
        pool = np.setdiff1d(np.arange(len(train)), labelled)
        if strategy == "uncertainty":
            probs = predictor.predict_proba(train.iloc[pool]["narration"].tolist())
            picked = pool[np.argsort(-entropy(probs), kind="stable")[:batch]]
        else:
            picked = pick_rng.choice(pool, size=batch, replace=False)
        labelled.extend(picked.tolist())  # oracle reveals train.csv labels for these rows
    return curve


def labels_to_reach(curve: list[tuple[int, float]], target: float) -> int | None:
    return next((n for n, f1 in curve if f1 >= target), None)


def build_markdown(results: dict, full_f1: float, args) -> str:
    target = TARGET_FRACTION * full_f1
    seeds = args.seeds
    lines = [
        "# Active learning: uncertainty vs random sampling",
        "",
        f"Generated by `python -m remark.active_loop`. Baseline (TF-IDF + LR) retrained each round; "
        f"seed set {args.seed_labels} labels, batch {args.batch}, {args.rounds} rounds, "
        f"random seeds {seeds}. Test macro-F1 shown as mean [min, max] over seeds.",
        "",
        f"Full-train baseline ({args.n_train} labels) test macro-F1: **{full_f1:.4f}**; "
        f"target = {TARGET_FRACTION:.0%} of that = **{target:.4f}**.",
        "",
        "| Labels | Uncertainty | Random |",
        "|---:|---:|---:|",
    ]
    n_points = len(results["uncertainty"][seeds[0]])
    for i in range(n_points):
        n = results["uncertainty"][seeds[0]][i][0]
        cells = []
        for strategy in STRATEGIES:
            values = np.array([results[strategy][s][i][1] for s in seeds])
            cells.append(f"{values.mean():.4f} [{values.min():.4f}, {values.max():.4f}]")
        lines.append(f"| {n} | " + " | ".join(cells) + " |")
    lines += ["", "## Labels needed to reach the target", "",
              "| Strategy | " + " | ".join(f"seed {s}" for s in seeds) + " | Mean |",
              "|---|" + "---:|" * (len(seeds) + 1)]
    for strategy in STRATEGIES:
        needed = [labels_to_reach(results[strategy][s], target) for s in seeds]
        reached = [n for n in needed if n is not None]
        mean = (f"{np.mean(reached):.0f}" if len(reached) == len(needed)
                else f"not reached in {len(needed) - len(reached)}/{len(needed)} seeds")
        lines.append(f"| {strategy} | " + " | ".join("—" if n is None else str(n) for n in needed)
                     + f" | {mean} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> dict:
    parser = argparse.ArgumentParser(description="Simulated active learning")
    parser.add_argument("--strategy", choices=(*STRATEGIES, "both"), default="both")
    parser.add_argument("--seed-labels", type=int, default=60)
    parser.add_argument("--batch", type=int, default=30)
    parser.add_argument("--rounds", type=int, default=10)
    parser.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--data", type=Path, default=Path("data"))
    parser.add_argument("--reports", type=Path, default=Path("reports"))
    args = parser.parse_args(argv)

    train, test = load_split(args.data, "train"), load_split(args.data, "test")
    strategies = STRATEGIES if args.strategy == "both" else (args.strategy,)
    results = {s: {seed: run(s, train, test, seed, args.seed_labels, args.batch, args.rounds)
                   for seed in args.seeds} for s in strategies}
    for strategy, by_seed in results.items():
        for seed, curve in by_seed.items():
            print(f"{strategy:11s} seed {seed}: " + " ".join(f"{n}:{f1:.3f}" for n, f1 in curve))
    if args.strategy == "both":
        _, full_f1 = fit_and_score(train, test)
        args.n_train = len(train)
        out = args.reports / "active_learning.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(build_markdown(results, full_f1, args))
        print(f"wrote {out}")
    return results


if __name__ == "__main__":
    main()
