"""Build reports/comparison.md from the training and bench reports.

    python -m remark.compare [--reports reports/] [--models models/]

Both models are evaluated on the identical test.csv by their training commands;
this module only reads their JSON reports (it never touches data).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from remark.labels import RISKY_LABELS

MODELS = ("baseline", "finetuned")


def dir_size_mb(path: Path) -> float | None:
    if not path.exists():
        return None
    return sum(f.stat().st_size for f in path.rglob("*") if f.is_file()) / 1e6


def _load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def _fmt(value, spec: str = ".3f") -> str:
    return "n/a" if value is None else format(value, spec)


def rows_for(report: dict | None, bench: dict | None, size_mb: float | None) -> dict[str, str]:
    if report is None:
        return {}
    t, c = report["test"], report["calibration"]
    rows = {
        "Test macro-F1": _fmt(t["macro_f1"]),
        "Macro-F1, held-out templates": _fmt(t["holdout_templates"]["macro_f1"]),
        "Macro-F1, in-distribution": _fmt(t["in_distribution"]["macro_f1"]),
    }
    rows.update({f"Recall {label}": _fmt(t["per_class"][label]["recall"]) for label in RISKY_LABELS})
    rows.update({
        "Temperature (fit on val)": _fmt(c["temperature"]),
        f"ECE before ({c['ece_bins']} bins)": _fmt(c["ece_before"]),
        "ECE after": _fmt(c["ece_after"]),
        "NLL before": _fmt(c["nll_before"]),
        "NLL after": _fmt(c["nll_after"]),
        "Alert threshold (val, >=90% risky recall)": _fmt(c["alerting"]["threshold"], ".4f"),
        "Test recall at threshold": _fmt(c["alerting"]["recall"]),
        "Test precision at threshold": _fmt(c["alerting"]["precision"]),
        "Alerts per 1,000 txns (test)": _fmt(c["alerting"]["alerts_per_1000"], ".1f"),
        "p95 latency, ms (bench.py)": _fmt(bench and bench["p95_ms"], ".2f"),
        "Model size on disk, MB": _fmt(size_mb, ".2f"),
        "Training time, s (CPU)": _fmt(report["train_seconds"], ".1f"),
        "Parameters (total / trainable)": (
            f"{report['parameters']['total']:,} / {report['parameters']['trainable']:,}"
            if "parameters" in report else "n/a (sparse linear)"),
    })
    return rows


def build_markdown(reports_dir: Path, models_dir: Path) -> str:
    columns = {}
    for name in MODELS:
        columns[name] = rows_for(_load(reports_dir / f"{name}.json"),
                                 _load(reports_dir / f"bench_{name}.json"),
                                 dir_size_mb(models_dir / name))
    metrics = next((list(c) for c in columns.values() if c), [])
    lines = [
        "# Baseline vs fine-tuned model",
        "",
        "Generated by `python -m remark.compare`. Both models are scored on the same `data/test.csv`;",
        "temperature and threshold were fitted on `data/val.csv` only.",
        "",
        "| Metric | " + " | ".join(MODELS) + " |",
        "|---|" + "---:|" * len(MODELS),
    ]
    for metric in metrics:
        lines.append(f"| {metric} | " + " | ".join(columns[m].get(metric, "n/a") for m in MODELS) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Write reports/comparison.md")
    parser.add_argument("--reports", type=Path, default=Path("reports"))
    parser.add_argument("--models", type=Path, default=Path("models"))
    args = parser.parse_args(argv)
    out = args.reports / "comparison.md"
    out.write_text(build_markdown(args.reports, args.models))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
